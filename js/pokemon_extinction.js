    function addFieldControls() {
        if ($("#ext-field").length) return;
        var html =
            '<div id="ext-field" class="btn-group" title="Pokémon Extinction field effects">' +
            '<input class="visually-hidden calc-trigger" type="checkbox" id="ext-trickroom" />' +
            '<label class="btn btn-small btn-left" for="ext-trickroom">Trick Room</label>' +
            '<input class="visually-hidden calc-trigger" type="checkbox" id="ext-swampL" />' +
            '<label class="btn btn-small btn-mid" for="ext-swampL" title="Swamp on your side: grounded Pokemon have 1/4 Speed">Swamp (you)</label>' +
            '<input class="visually-hidden calc-trigger" type="checkbox" id="ext-swampR" />' +
            '<label class="btn btn-small btn-right" for="ext-swampR" title="Swamp on the trainer\'s side">Swamp (foe)</label>' +
            '</div>' +
            '<div id="ext-field-notes" class="ext-field-notes"></div>';
        $("#gravity").parent().after(html);
        $("#ext-field input").on("change", function () {
            if (typeof performCalculations === "function") performCalculations();
        });
    }

    function checkTerrain(name) {
        $('input[name="terrain"]').prop("checked", false);
        if (name) $('input[name="terrain"][value="' + name + '"]').prop("checked", true);
    }

    function checkWeather(value) {
        var input = $('input[name="weather"][value="' + value + '"]');
        if (input.length) input.prop("checked", true);
    }

    // Starting Status names exactly as trainers.party spells them.
    var WEATHER_STATUSES = {
        "Sun": "Sun", "Rain": "Rain", "Sandstorm": "Sand", "Sand": "Sand", "Snow": "Snow", "Hail": "Hail",
        "Desolate Land": "Harsh Sunshine", "Primordial Sea": "Heavy Rain", "Delta Stream": "Strong Winds",
    };
    var TERRAIN_STATUSES = {
        "Electric Terrain": "Electric", "Grassy Terrain": "Grassy",
        "Misty Terrain": "Misty", "Psychic Terrain": "Psychic",
    };

    function applyTrainerField(info) {
        var notes = [];

        // Reset what a trainer can set, so nothing carries over from the previous one.
        checkTerrain(null);
        $("#clear").prop("checked", true);
        $("#gravity, #srL, #srR, #steelsurgeL, #steelsurgeR, #ext-trickroom, #ext-swampL, #ext-swampR").prop("checked", false);
        $("#spikesL0, #spikesR0").prop("checked", true);

        if (info.map_weather) {
            checkWeather(info.map_weather);
            notes.push("Map weather: " + info.map_weather);
        }
        if (info.map_terrain) {
            checkTerrain(info.map_terrain);
            notes.push("Map fog: " + info.map_terrain + " Terrain");
        }

        (info.starting_status || []).forEach(function (status) {
            var base = status.replace(/ Temporary$/, "");
            var spikes = base.match(/^(Toxic )?Spikes (Player|Opponent) L(\d)$/);
            var side = / Player$/.test(base) ? "L" : / Opponent$/.test(base) ? "R" : null;

            if (WEATHER_STATUSES[base]) {
                checkWeather(WEATHER_STATUSES[base]);
            } else if (TERRAIN_STATUSES[base]) {
                checkTerrain(TERRAIN_STATUSES[base]);
            } else if (base === "Trick Room") {
                $("#ext-trickroom").prop("checked", true);
            } else if (base === "Gravity") {
                $("#gravity").prop("checked", true);
            } else if (base === "Torment Weather") {
                $("#clear").prop("checked", true); // replaces any other weather; residual damage only
            } else if (/^Stealth Rock/.test(base) && side) {
                $("#sr" + side).prop("checked", true);
            } else if (/^Sharp Steel/.test(base) && side) {
                $("#steelsurge" + side).prop("checked", true);
            } else if (spikes && !spikes[1]) {
                $("#spikes" + (spikes[2] === "Player" ? "L" : "R") + spikes[3]).prop("checked", true);
            } else if (/^Swamp/.test(base) && side) {
                $("#ext-swamp" + side).prop("checked", true);
            }
            notes.push(status);
        });

        $("#ext-field-notes").text(notes.length ? notes.join(" · ") : "");
    }

    var lastTrainerId = null;

    function onOpposingSetChange() {
        if (!isExtinction()) return;
        var fullSetName = $(this).val() || "";
        var pokemonName = fullSetName.substring(0, fullSetName.indexOf(" ("));
        var setName = fullSetName.substring(fullSetName.indexOf("(") + 1, fullSetName.lastIndexOf(")"));
        var set = setdex && setdex[pokemonName] ? setdex[pokemonName][setName] : null;
        var info = set && extinctionData().trainer_info ? extinctionData().trainer_info[set.tr_id] : null;
        if (!info || set.tr_id === lastTrainerId) return; // keep manual field changes within one fight
        lastTrainerId = set.tr_id;
        // After the core handler, which resets the field and picks singles/doubles.
        setTimeout(function () {
            applyTrainerField(info);
            if (typeof performCalculations === "function") performCalculations();
        }, 50);
    }

    // ------------------------------------------------------------------------------------------
    // Mega / Primal toggle
    //
    // A trainer's Mega holds its stone and evolves on its first turn, so both forms matter: the base
    // form takes the hit on the turn it comes in, the Mega does everything after. The Form dropdown
    // can already switch between them; this is the one-click version of it, and it shows up only
    // when the held item actually changes the form.
    // ------------------------------------------------------------------------------------------

    // The ability list holds the abilities the calc knows; a hack-only one is added so it at least
    // shows, even though the damage engine has no behaviour for it.
    function setAbility(panel, ability) {
        if (!ability) return;
        var select = panel.find(".ability");
        if (!select.find('option[value="' + ability + '"]').length) {
            select.append($("<option>").attr("value", ability).text(ability));
        }
        select.val(ability).change();
    }

    // Upstream only refreshes the left sprite when the form changes.
    window.updateRightPokeSprite = function (speciesName) {
        var name = (typeof getSpriteSpeciesName === "function" ? getSpriteSpeciesName(speciesName) : speciesName)
            .toLowerCase().replace(" ", "").replace(".", "").replace("\u2019", "").replace(":", "-").replace(/-s$/, "");
        if (name.indexOf("galarian-") === 0) name = name.slice("galarian-".length) + "-galar";
        if (name.indexOf("hisuian-") === 0) name = name.slice("hisuian-".length) + "-hisui";
        if (name.indexOf("alolan-") === 0) name = name.slice("alolan-".length) + "-alola";
        var style = typeof trainerSprites !== "undefined" ? trainerSprites : "front";
        var ext = typeof suffix !== "undefined" && suffix ? suffix : "png";
        $("#p2 .poke-sprite").attr("src", "./img/" + style + "/" + name.replace("-glitched", "") + "." + ext);
    };

    function formTarget(item, formeSelect) {
        if (!item) return null;
        var stones = (typeof calc !== "undefined" && calc.MEGA_STONES) || {};
        var candidates = [];
        if (stones[item]) {
            // Older entries map a stone to the base species, newer ones straight to the Mega.
            // Charizardite X / Mewtwonite Y and friends pick one of two Megas, named by the suffix.
            var suffix = (item.match(/ (X|Y)$/) || [])[1];
            candidates.push(stones[item]);
            if (suffix) candidates.push(stones[item] + "-Mega-" + suffix);
            candidates.push(stones[item] + "-Mega");
        }
        if (item === "Red Orb") candidates.push("Groudon-Primal");
        if (item === "Blue Orb") candidates.push("Kyogre-Primal");
        for (var i = 0; i < candidates.length; i++) {
            if (/-(Mega|Primal)/.test(candidates[i]) && formeSelect.find('option[value="' + candidates[i] + '"]').length) {
                return candidates[i];
            }
        }
        return null;
    }

    // The Form dropdown is built from the calc's own data, so it offers forms this ROM does not
    // have (Sevii forms, Megas the hack never added) and both Mega Charizards whatever stone is
    // held. A Pokemon can only reach the form its item gives it, so drop the rest.
    function filterFormeOptions(panel, target) {
        var formeSelect = $(panel).find(".forme");
        var poks = extinctionData().poks || {};
        var current = formeSelect.val();
        formeSelect.find("option").each(function () {
            var name = $(this).attr("value");
            if (name === current) return;
            var unreachableForm = /-(Mega|Primal)/.test(name) && name !== target;
            if (!poks[name] || unreachableForm) $(this).remove();
        });
        // Nothing left to choose between: the calc hides a single-option dropdown anyway.
        formeSelect.closest("div").toggleClass("hide", formeSelect.find("option").length < 2 && !target);
    }

    function updateFormToggle(panel) {
        var formeSelect = $(panel).find(".forme");
        var item = $(panel).find(".item").val();
        var button = $(panel).find(".ext-form-toggle");
        var current = formeSelect.val() || "";
        // Switching to a Mega clears the stone in the calc, so once a Mega or Primal form is
        // selected the current form is what tells us where to switch back to.
        var target = /-(Mega|Primal)/.test(current) ? current : formTarget(item, formeSelect);

        if (!isExtinction()) {
            button.remove();
            return;
        }
        if (!target) {
            filterFormeOptions(panel, null);
            button.remove();
            return;
        }
        if (!button.length) {
            button = $('<button type="button" class="bs-btn ext-form-toggle"></button>');
            formeSelect.closest("div").removeClass("hide").append(button);
            button.on("click", function () {
                var to = $(this).attr("data-to");
                var stone = $(this).attr("data-item");
                var back = $(this).attr("data-ability");
                $(panel).find(".forme").val(to).change();
                // Mega Evolving clears the stone in the calc; put it back on the way down.
                if (stone && !$(panel).find(".item").val()) {
                    $(panel).find(".item").val(stone).change();
                }
                // The forme change re-applies the SET's ability, which belongs to the base form.
                // A Mega has its own (Mega Ampharos is Fluffy in this hack, not Static).
                var wanted = /-(Mega|Primal)/.test(to)
                    ? (window.pokedex && pokedex[to] && pokedex[to].abilities && pokedex[to].abilities[0])
                    : back;
                setAbility($(panel), wanted);
            });
        }
        filterFormeOptions(panel, target);
        var isBase = current !== target;
        var label = /-Primal/.test(target) ? "Primal" : "Mega";
        if (isBase && item) button.attr("data-item", item); // remember the stone for the way back
        if (isBase) button.attr("data-ability", $(panel).find(".ability").val() || "");
        button.text(isBase ? "\u2192 " + label : "\u2192 Base")
              .attr("data-to", isBase ? target : target.replace(/-(Mega.*|Primal)$/, ""));
    }

    function updateFormToggles() {
        preferBoxSetName();
        updateFormToggle("#p1");
        updateFormToggle("#p2");
        updateBoxTag();
    }

