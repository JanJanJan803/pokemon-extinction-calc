    function getOwned() {
        try {
            return JSON.parse(localStorage.getItem(OWNED_KEY) || "[]");
        } catch (e) {
            return [];
        }
    }

    function setOwned(list) {
        try {
            localStorage.setItem(OWNED_KEY, JSON.stringify(list));
        } catch (e) { /* private window: the picker still works for this visit */ }
    }

    var STAT_LABELS = [["hp", "HP"], ["at", "Atk"], ["df", "Def"], ["sa", "SpA"], ["sd", "SpD"], ["sp", "Spe"]];

    function showdownText(species, set) {
        var lines = [species + (set.item ? " @ " + set.item : "")];
        lines.push("Level: " + set.level);
        lines.push(set.nature + " Nature");
        if (set.ability) lines.push("Ability: " + set.ability);
        lines.push("IVs: " + STAT_LABELS.map(function (s) { return set.ivs[s[0]] + " " + s[1]; }).join(" / "));
        set.moves.forEach(function (m) { lines.push("- " + m); });
        return lines.join("\n");
    }

    function spriteSrc(species) {
        var name = typeof getPreviewSpriteName === "function" ? getPreviewSpriteName(species) : species.toLowerCase();
        var style = typeof sprite_style !== "undefined" ? sprite_style : "newhd";
        return "./img/" + style + "/" + name + ".png";
    }

    function poolGroups() {
        var groups = {};
        var sets = extinctionData().player_sets || {};
        Object.keys(sets).sort().forEach(function (species) {
            Object.keys(sets[species]).forEach(function (label) {
                var pool = label.replace(/ #\d+$/, "");
                (groups[pool] = groups[pool] || []).push({ species: species, label: label, set: sets[species][label] });
            });
        });
        return groups;
    }

    function boxOf(pool) {
        var m = pool.match(/^Box (\d+)/);
        return m ? m[1] : pool;
    }

    function renderPicker() {
        var owned = getOwned();
        var groups = poolGroups();
        var boxes = {};
        Object.keys(groups).sort().forEach(function (pool) {
            (boxes[boxOf(pool)] = boxes[boxOf(pool)] || []).push(pool);
        });
        var html = "";
        Object.keys(boxes).sort().forEach(function (box) {
            html += '<div class="ext-box" data-box="' + box + '"><h3>Box ' + box +
                ' <button type="button" class="bs-btn ext-box-import" data-box="' + box + '">Import Box ' + box +
                '</button></h3>';
            boxes[box].forEach(function (pool) {
                var sub = pool.replace(/^Box \d+\s*/, "");
                html += '<h4>' + (sub || "Pool") + '</h4><div class="ext-pool">';
                groups[pool].forEach(function (entry) {
                    var key = entry.species + "|" + entry.label;
                    var set = entry.set;
                    var tip = entry.species + " Lv" + set.level + " (" + set.nature + ", " + set.ability + ")" +
                        (set.item ? " @ " + set.item : "") + "\n" + set.moves.join(", ");
                    html += '<div class="ext-mon' + (owned.indexOf(key) !== -1 ? " owned" : "") + '" data-key="' +
                        key.replace(/"/g, "&quot;") + '" title="' + tip.replace(/"/g, "&quot;") + '">' +
                        '<img src="' + spriteSrc(entry.species) + '" loading="lazy" alt="">' +
                        '<span>' + entry.species + '</span></div>';
                });
                html += "</div>";
            });
            html += "</div>";
        });
        $("#ext-box-list").html(html);
        $("#ext-box-count").text(owned.length + " selected");
    }

    var LABELS_KEY = "extinctionBoxLabels";

    function getBoxLabels() {
        try {
            return JSON.parse(localStorage.getItem(LABELS_KEY) || "{}");
        } catch (e) {
            return {};
        }
    }

    // The calc stores every imported mon under one set name, "My Box", so the list would read
    // "Charizard (My Box)" whichever box it came from.
    //
    // Rather than rewrite the label - the species and set name are parsed back out of it in around
    // thirty places - the box name is registered as a second name for the same set object, and the
    // "My Box" entry is hidden from the lists. "Charizard (Box 5 Starter)" is then a real set that
    // every one of those places can still look up. Only setdex gets the extra name; the stored box
    // in localStorage stays keyed by "My Box", which the box view and fragsheet rely on.
    var aliasedSets = [];

    function syncBoxSetNames() {
        if (typeof setdex !== "object" || !setdex) return;
        aliasedSets.forEach(function (entry) {
            if (setdex[entry[0]]) delete setdex[entry[0]][entry[1]];
        });
        aliasedSets = [];
        Object.keys(setdex).forEach(function (species) {
            var boxSet = setdex[species] && setdex[species]["My Box"];
            var label = boxSet && boxLabelFor(species);
            if (!label || label === "My Box" || setdex[species][label]) return;
            setdex[species][label] = boxSet;
            aliasedSets.push([species, label]);
        });
    }

    function decorateBoxOptions(options) {
        syncBoxSetNames();
        return options.filter(function (option) {
            // Hide the raw "My Box" row when the same set is listed under its box name.
            return !(option && option.set === "My Box" && boxLabelFor(option.pokemon));
        });
    }

    function boxLabelFor(speciesName) {
        var labels = getBoxLabels();
        if (labels[speciesName]) return labels[speciesName];
        // Megas the calc derives from a box mon (Abomasnow-Mega) inherit the base mon's box.
        var base = String(speciesName || "").replace(/-(Mega.*|Primal)$/, "");
        return labels[base] || "";
    }

    // Clicking a box icon selects the set by its stored name, so the label would read "(My Box)"
    // again. Both names point at the same set, so the label can be swapped without re-applying it.
    function preferBoxSetName() {
        var selector = $("#p1 .set-selector").first();
        var value = selector.val() || "";
        var match = value.match(/^(.*) \(My Box\)$/);
        var label = match && boxLabelFor(match[1]);
        if (!label) return;
        var renamed = match[1] + " (" + label + ")";
        if (typeof setdex === "object" && setdex[match[1]] && setdex[match[1]][label]) {
            selector.val(renamed);
            $("#p1 .select2-chosen").first().text(renamed);
        }
    }

    // A tag next to the Pokemon list also names the box, for the panel itself.
    function updateBoxTag() {
        var chosen = $("#p1 .set-selector").first().val() || $("#p1 .select2-chosen").first().text() || "";
        var species = chosen.split(" (")[0].trim();
        var isBoxSet = /\(([^)]*)\)\s*$/.test(chosen) && !!boxLabelFor(species);
        var label = isBoxSet ? boxLabelFor($("#p1 .forme").val() || species) : "";
        var tag = $("#ext-box-tag");
        if (!tag.length) {
            tag = $('<div id="ext-box-tag" class="ext-box-tag"></div>');
            $("#p1 .set-selector").first().closest("div").after(tag);
        }
        tag.text(label).toggle(!!label);
    }

    function importOwned() {
        var sets = extinctionData().player_sets || {};
        // The calc keeps one box set per species. When two pools share a species, import the later
        // box last so its set is the one kept - that is the version a player has later in the game.
        var keys = getOwned().slice().sort(function (a, b) {
            var la = a.slice(a.indexOf("|") + 1), lb = b.slice(b.indexOf("|") + 1);
            return la < lb ? -1 : la > lb ? 1 : 0;
        });
        var texts = keys.map(function (key) {
            var sep = key.indexOf("|");
            var species = key.slice(0, sep);
            var set = sets[species] && sets[species][key.slice(sep + 1)];
            return set ? showdownText(species, set) : null;
        }).filter(Boolean);

        // Replace the box rather than merging: a new split wipes the player's old encounters.
        // updateDex compares against the STORED box to know what to remove, so the stored box must
        // still be the old one when it runs - it then stores the result itself. Only "My Box" sets
        // are touched; the trainer sets live in the same table and stay.
        if (typeof updateDex === "function" && typeof getStoredCustomSets === "function" &&
            typeof removeMyBoxEntries === "function") {
            updateDex(removeMyBoxEntries(getStoredCustomSets()));
            customSets = getStoredCustomSets();
        }
        // The party and the left-side selection point at the old box.
        $("#clear-party").click();
        try {
            if (/\(My Box\)$/.test(localStorage.left || "")) localStorage.removeItem("left");
        } catch (e) { /* storage unavailable */ }

        var labels = {};
        keys.forEach(function (key) {
            var sep = key.indexOf("|");
            labels[key.slice(0, sep)] = key.slice(sep + 1).replace(/ #\d+$/, "");
        });
        try {
            localStorage.setItem(LABELS_KEY, JSON.stringify(labels));
        } catch (e) { /* storage unavailable */ }

        if (texts.length && typeof addSets === "function") {
            addSets(texts.join("\n\n"), "My Box");
            syncBoxSetNames();
            // Show a Pokemon from the new box instead of one that no longer exists.
            $(".player-poks .trainer-pok, .player-megas .trainer-pok").first().click();
        } else if (typeof get_box === "function") {
            get_box();
        }
    }

    function addBoxPicker() {
        if ($("#ext-box-open").length) return;
        $("#read-save").hide();
        $(".import-team-text").attr("placeholder", "Use \"Pokémon Extinction Box\" to pick the box Pokemon you received.");
        $("#read-save").after('<button type="button" class="bs-btn bs-btn-default" id="ext-box-open">Pokémon Extinction Box</button>');
        $("body").append(
            '<div id="ext-box-modal" class="ext-modal" hidden>' +
            '<div class="ext-modal-dialog" role="dialog" aria-label="Pokémon Extinction box">' +
            '<div class="ext-modal-head"><strong>Which box Pokemon did you get?</strong>' +
            '<span id="ext-box-count"></span>' +
            '<button type="button" class="bs-btn" id="ext-box-none">Unselect all</button>' +
            '<button type="button" class="bs-btn" id="ext-box-import">Import selected</button>' +
            '<button type="button" class="bs-btn" id="ext-box-close">Close</button></div>' +
            '<p class="ext-modal-help">"Import Box N" imports that whole box. Or click single Pokemon and use "Import selected". ' +
            'Every import replaces the previously imported Pokemon; importing nothing empties the box. Hover for a set; held items can be changed on the left after importing.</p>' +
            '<div id="ext-box-list"></div></div></div>'
        );

        $("#ext-box-open").on("click", function () {
            renderPicker();
            $("#ext-box-modal").prop("hidden", false);
        });
        $("#ext-box-close").on("click", function () {
            $("#ext-box-modal").prop("hidden", true);
        });
        $("#ext-box-import").on("click", function () {
            importOwned();
            $("#ext-box-modal").prop("hidden", true);
        });
        // A new split hands out a new box and wipes the old one, so importing a box replaces
        // whatever was imported before.
        $("#ext-box-none").on("click", function () {
            setOwned([]);
            renderPicker();
        });
        $("#ext-box-list").on("click", ".ext-box-import", function () {
            var box = $(this).attr("data-box");
            setOwned($('#ext-box-list .ext-box[data-box="' + box + '"] .ext-mon').map(function () {
                return $(this).attr("data-key");
            }).get());
            importOwned();
            $("#ext-box-modal").prop("hidden", true);
        });
        $("#ext-box-list").on("click", ".ext-mon", function () {
            var key = $(this).attr("data-key");
            var owned = getOwned();
            var at = owned.indexOf(key);
            if (at === -1) owned.push(key); else owned.splice(at, 1);
            setOwned(owned);
            $(this).toggleClass("owned", at === -1);
            $("#ext-box-count").text(owned.length + " selected");
        });
    }

    // ------------------------------------------------------------------------------------------

    $(document).on("change", ".opposing.set-selector", onOpposingSetChange);
    $(document).on("change", ".set-selector, .item, .forme", function () {
        setTimeout(updateFormToggles, 60); // after the panel is rebuilt
    });

    $(function () {
        // backup_data loads asynchronously; wait for it before building the Extinction-only UI.
        var tries = 0;
        var timer = setInterval(function () {
            tries++;
            if (isExtinction() && extinctionData().player_sets) {
                clearInterval(timer);
                addFieldControls();
                addBoxPicker();
                updateFormToggles();
                if (typeof getSetOptions === "function" && !getSetOptions.extinctionWrapped) {
                    var original = getSetOptions;
                    window.getSetOptions = function (sets) {
                        var options = original(sets);
                        return isExtinction() ? decorateBoxOptions(options) : options;
                    };
                    window.getSetOptions.extinctionWrapped = true;
                }
            } else if (tries > 200) {
                clearInterval(timer);
            }
        }, 50);
    });
