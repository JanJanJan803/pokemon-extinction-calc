    function isGrounded(pokemon) {
        if ($("#gravity").prop("checked")) return true;
        if (pokemon.hasItem && pokemon.hasItem("Iron Ball")) return true;
        if (pokemon.hasType && pokemon.hasType("Flying")) return false;
        if (pokemon.hasAbility && pokemon.hasAbility("Levitate")) return false;
        if (pokemon.hasItem && pokemon.hasItem("Air Balloon")) return false;
        return true;
    }

    function affectedBySwamp(pokemon) {
        if (!pokemon) return true;
        if (pokemon.hasItem && pokemon.hasItem("Heavy-Duty Boots")) return false;
        if (pokemon.hasAbility && pokemon.hasAbility("Magic Guard")) return false;
        return isGrounded(pokemon);
    }

    // Called from performCalculations with the final Speed stats. Swamp is the Grass/Water Pledge
    // side effect: a quarter of the Speed for grounded mons without Boots or Magic Guard.
    window.extinctionAdjustSpeeds = function (spe1, spe2, p1, p2) {
        var out = { p1: spe1, p2: spe2, trickRoom: false };
        if (!isExtinction()) return out;
        if ($("#ext-swampL").prop("checked") && affectedBySwamp(p1)) out.p1 = Math.floor(spe1 / 4);
        if ($("#ext-swampR").prop("checked") && affectedBySwamp(p2)) out.p2 = Math.floor(spe2 / 4);
        out.trickRoom = $("#ext-trickroom").prop("checked");
        return out;
    };

